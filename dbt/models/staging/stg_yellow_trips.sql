with source as (
    select
        trip_id,
        vendorid,
        tpep_pickup_datetime,
        tpep_dropoff_datetime,
        passenger_count,
        trip_distance,
        ratecodeid,
        store_and_fwd_flag,
        pulocationid,
        dolocationid,
        payment_type,
        fare_amount,
        extra,
        mta_tax,
        tip_amount,
        tolls_amount,
        improvement_surcharge,
        total_amount,
        congestion_surcharge,
        airport_fee,
        service,
        source_file,
        source_row_number,
        ingested_at,
        content_hash,
        pickup_year,
        pickup_month
    from {{ source('bronze', 'tlc_trips') }}
)

select
    trip_id,
    cast(vendorid as integer) as vendor_id,
    with_timezone(cast(tpep_pickup_datetime as timestamp), 'America/New_York') as pickup_at,
    with_timezone(cast(tpep_dropoff_datetime as timestamp), 'America/New_York') as dropoff_at,
    cast(passenger_count as bigint) as passenger_count,
    cast(trip_distance as double) as trip_distance,
    cast(ratecodeid as bigint) as ratecode_id,
    cast(store_and_fwd_flag as varchar) as store_and_fwd_flag,
    cast(pulocationid as integer) as pickup_location_id,
    cast(dolocationid as integer) as dropoff_location_id,
    cast(payment_type as bigint) as payment_type,
    cast(fare_amount as decimal(12, 2)) as fare_amount,
    cast(extra as decimal(12, 2)) as extra,
    cast(mta_tax as decimal(12, 2)) as mta_tax,
    cast(tip_amount as decimal(12, 2)) as tip_amount,
    cast(tolls_amount as decimal(12, 2)) as tolls_amount,
    cast(improvement_surcharge as decimal(12, 2)) as improvement_surcharge,
    cast(total_amount as decimal(12, 2)) as total_amount,
    cast(congestion_surcharge as decimal(12, 2)) as congestion_surcharge,
    cast(airport_fee as decimal(12, 2)) as airport_fee,
    cast(service as varchar) as service,
    cast(source_file as varchar) as source_file,
    cast(source_row_number as bigint) as source_row_number,
    cast(ingested_at as timestamp(3) with time zone) as ingested_at,
    cast(content_hash as varchar) as content_hash,
    cast(pickup_year as integer) as pickup_year,
    cast(pickup_month as integer) as pickup_month
from source
